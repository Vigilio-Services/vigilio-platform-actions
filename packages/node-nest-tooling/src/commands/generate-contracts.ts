#!/usr/bin/env node

import fs from 'node:fs/promises';
import path from 'node:path';

const exportableDirectories = new Set(['dtos', 'schemas', 'responses', 'types']);
const ignoredFilePatterns = [
  /\.d\.ts$/,
  /\.spec\.ts$/,
  /\.test\.ts$/,
  /\.steps\.ts$/,
  /\.class\.dto\.ts$/,
  /\.doc\.ts$/,
  /(^|[\\/])index\.ts$/,
  /(^|[\\/])contracts\.ts$/,
];

const forbiddenPublicImports = [
  { label: 'NestJS', pattern: /(?:from\s+|import\s*\(\s*|import\s+)['"]@nestjs\// },
  {
    label: 'nestjs-zod',
    pattern: /(?:from\s+|import\s*\(\s*|import\s+)['"]nestjs-zod['"]/,
  },
  { label: 'Node.js built-in', pattern: /(?:from\s+|import\s*\(\s*|import\s+)['"]node:/ },
];

async function getFiles(directory: string): Promise<string[]> {
  const dirents = await fs.readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    dirents.map((dirent) => {
      const resolvedPath = path.resolve(directory, dirent.name);
      return dirent.isDirectory() ? getFiles(resolvedPath) : resolvedPath;
    }),
  );

  return files.flat();
}

function isInsideExportableDirectory(file: string, srcDirectory: string): boolean {
  const relativeParts = path.relative(srcDirectory, file).split(path.sep);
  return relativeParts.some((part) => exportableDirectories.has(part));
}

function isIgnoredFile(file: string): boolean {
  return ignoredFilePatterns.some((pattern) => pattern.test(file));
}

function toExportLine(file: string, srcDirectory: string): string {
  const relativePath = path.relative(srcDirectory, file);
  const importPath = relativePath.replace(/\\/g, '/').replace(/\.ts$/, '');
  return `export * from "./${importPath}";`;
}

async function generateContracts(): Promise<void> {
  const srcDirectory = path.resolve(process.cwd(), 'src');
  const contractsPath = path.resolve(srcDirectory, 'contracts.ts');
  const allFiles = await getFiles(srcDirectory);

  const publicContractFiles = allFiles
    .filter((file) => file.endsWith('.ts'))
    .filter((file) => isInsideExportableDirectory(file, srcDirectory))
    .filter((file) => !isIgnoredFile(file));

  await validateBrowserSafeContracts(publicContractFiles, srcDirectory);

  const exportLines = publicContractFiles.map((file) => toExportLine(file, srcDirectory)).sort();

  const header = [
    '// AUTO-GENERATED FILE - DO NOT EDIT',
    '// Generated by vigilio-node generate-contracts',
    '// Browser-safe public contracts from dtos/, schemas/, responses/ and types/ folders.',
    '// NestJS/OpenAPI adapters (*.doc.ts) are backend-only and intentionally excluded.',
    '',
  ].join('\n');

  await fs.writeFile(contractsPath, `${header}${exportLines.join('\n')}\n`);

  console.log(`Generated src/contracts.ts with ${exportLines.length} exports.`);
}

async function validateBrowserSafeContracts(files: string[], srcDirectory: string): Promise<void> {
  const violations: string[] = [];

  for (const file of files) {
    const content = await fs.readFile(file, 'utf8');
    for (const forbiddenImport of forbiddenPublicImports) {
      if (forbiddenImport.pattern.test(content)) {
        violations.push(`${path.relative(srcDirectory, file)} imports ${forbiddenImport.label}`);
      }
    }
  }

  if (violations.length === 0) return;

  throw new Error(
    [
      'Public contract generation failed: browser contracts must not import NestJS or Node.js built-ins.',
      ...violations.map((violation) => `- ${violation}`),
      'Move createZodDto/OpenAPI wrappers to a sibling *.doc.ts file and export only pure Zod schemas/types.',
    ].join('\n'),
  );
}

generateContracts().catch((error) => {
  console.error(error);
  process.exit(1);
});
