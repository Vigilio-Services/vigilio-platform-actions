import { describe, expect, it } from 'vitest';
import { validateCommitMessage, validatePrBody, validatePrTitle } from '../src/pr-policy.js';

describe('PR policy', () => {
  it('allows valid PR title', () => {
    expect(
      validatePrTitle('[ABC-123] - feat: Crear endoso', 'feat/ABC-123/crear-endoso'),
    ).toStrictEqual([]);
  });

  it('rejects PR title with different ticket', () => {
    expect(
      validatePrTitle('[ABC-999] - feat: Crear endoso', 'feat/ABC-123/crear-endoso'),
    ).toHaveLength(1);
  });

  it('rejects missing and malformed PR titles', () => {
    expect(validatePrTitle('')).toHaveLength(1);
    expect(validatePrTitle('feat: Crear endoso')).toHaveLength(2);
  });

  it('allows valid commit message', () => {
    expect(
      validateCommitMessage('[ABC-123] - fix: Corregir endoso', 'fix/ABC-123/corregir-endoso'),
    ).toStrictEqual([]);
  });

  it('rejects malformed and mismatched commit messages', () => {
    expect(validateCommitMessage('fix: Corregir endoso')).toHaveLength(2);
    expect(
      validateCommitMessage('[ABC-999] - fix: Corregir endoso', 'fix/ABC-123/corregir-endoso'),
    ).toHaveLength(1);
  });

  it('allows a matching GitOps promotion generated by the trusted bot', () => {
    const branch = 'gitops/promote-staging-0123456789ab';
    const subject = 'chore(gitops): promote bus-impl-v2 to staging';

    expect(validatePrTitle(subject, branch, 'github-actions[bot]')).toStrictEqual([]);
    expect(validateCommitMessage(subject, branch, 'github-actions[bot]')).toStrictEqual([]);
  });

  it('rejects spoofed or inconsistent GitOps promotions', () => {
    const branch = 'gitops/promote-production-0123456789ab';
    const subject = 'chore(gitops): promote bus-impl-v2 to production';

    expect(validatePrTitle(subject, branch, 'developer')).toHaveLength(2);
    expect(validateCommitMessage(subject, branch)).toHaveLength(2);
    expect(
      validatePrTitle(
        'chore(gitops): promote bus-impl-v2 to staging',
        branch,
        'github-actions[bot]',
      ),
    ).toHaveLength(2);
  });

  it('accepts a promotion from the configured GitHub App identity', () => {
    const branch = 'gitops/promote-production-0123456789ab';
    const subject = 'chore(gitops): promote invoice-api to production';

    expect(
      validatePrTitle(subject, branch, 'vigilio-gitops[bot]', 'vigilio-gitops[bot]'),
    ).toStrictEqual([]);
    expect(
      validateCommitMessage(subject, branch, 'vigilio-gitops[bot]', 'vigilio-gitops[bot]'),
    ).toStrictEqual([]);
  });

  it('rejects empty PR body', () => {
    expect(validatePrBody('## Descripcion obligatoria')).toHaveLength(1);
  });

  it('allows meaningful PR body', () => {
    expect(
      validatePrBody(
        'Se agrega validacion reusable para workflows, acciones y convenciones de ramas.',
      ),
    ).toStrictEqual([]);
  });
});
